# =============================================================================
# 自己検査：全ピンが「ネットに入っている」か「未接続宣言済み」かのどちらかであること
# =============================================================================
def check():
    problems = []

    used = {}
    for net, nodes in NETS.items():
        for ref, pin in nodes:
            if ref not in PARTS:
                problems.append(f"ネット {net}: 部品 {ref} が部品表にありません")
                continue
            if pin not in PARTS[ref]["pins"]:
                problems.append(f"ネット {net}: {ref} にピン {pin} がありません")
                continue
            key = (ref, pin)
            if key in used:
                problems.append(f"{ref}.{pin} が {used[key]} と {net} の両方に入っています（短絡）")
            used[key] = net

    nc = set(NO_CONNECT)
    for ref, part in PARTS.items():
        for pin in part["pins"]:
            if (ref, pin) not in used and (ref, pin) not in nc:
                problems.append(f"{ref}.{pin}（{part['pins'][pin]}）がどのネットにも入っていません")

    for ref, pin in NO_CONNECT:
        if (ref, pin) in used:
            problems.append(f"{ref}.{pin} は未接続宣言なのに {used[(ref,pin)]} に繋がっています")

    for net, nodes in NETS.items():
        if len(nodes) < 2:
            problems.append(f"ネット {net} に接続先が1つしかありません")

    return problems


if __name__ == "__main__":
    probs = check()
